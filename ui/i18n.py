def t(key: str) -> str:
    """Traduit une cle vers la langue active (st.session_state.lang)."""
    lang = st.session_state.get("lang", "FR")
    return TRANSLATIONS[lang].get(key, key)


def L(lang: str, fr: str, en: str) -> str:
    """Retourne fr ou en selon la langue donnee explicitement (hors session_state)."""
    return fr if lang == "FR" else en
